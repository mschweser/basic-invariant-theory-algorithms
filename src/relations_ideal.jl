using Oscar

# input: f_1, ..., f_m in k[x_1, ..., x_n] and ring R = k[x_1, ..., x_n]
# so that R^G = k[f_1, ..., f_m]
# output: (I_F, GG_y) where I_F is ideal of relations 
# so that R^G is isomorphic to k[y_1, ..., y_m] / I_F 
# and GG_y is groebner basis of I_F

# use theorem 4.1.4
# algorithm:
# 1. compute groebner basis GG of JF = < f_1 - y_1, ..., f_m - y_m>
# 2. take all polynomials in GG_y := GG \cap k[y_1, ..., y_m]
# 3. the relation ideal I_F = < GG_y> and GG_y is a groebner basis of I_F

function relations_ideal(F::AbstractVector, R::Union{PolyRing, MPolyRing})
    K = base_ring(R) # R = k[x_1, ..., x_n] with field k
    K isa Field || error("The coefficient ring must be a field.") # convention

    if isempty(F) # for empty F, R^G = k and k[y_1, ..., y_m] = k and I_F = (0)
        S, _ = polynomial_ring(K, Symbol[])
        GG_y = elem_type(S)[]
        I_F = ideal(S, GG_y)
        return I_F, GG_y
    end

    # all generators must be a polynomial in R or coercible into its coefficient field k
    for fi in F
        if fi isa Union{PolyRingElem, MPolyRingElem}
            parent(fi) === R || error("All polynomial generators must belong to R.")
        else
            try
                K(fi) # coerce constant into coefficient field
            catch
                error("Every constant generator must be coercible into the coefficient field.")
            end
        end
    end

    # construct ideal J_F = <f_1 - y_1, ..., f_m - y_m> in ring 
    # S = k[x_1, ..., x_n, y_1, ..., y_m]
    n = ngens(R) # number of generators of R, Oscar function
    m = length(F) # number of generators of R^G in set F
    names = vcat([Symbol("x_$i") for i in 1:n], [Symbol("y_$i") for i in 1:m])
    S, z = polynomial_ring(K, names; internal_ordering = :lex)
    x = z[1:n] # x_1, ..., x_n in S
    y = z[n+1:n+m] # y_1, ..., y_m in S
    if R isa PolyRing # R is univariate, homomorphism method takes image of one generator
        phi = hom(R, S, x[1]) # phi : R = k[t] -> S = k[x_1, y_1, ..., y_m], t |-> x_1
    else # R is multivariate, homomorphism method takes vector of all generator images
        phi = hom(R, S, x) # phi : R = k[x_1, ..., x_n] -> S = k[x_1, ..., x_n, y_1, ..., y_m]
        # x_i |-> x_i
    end
    F_S = elem_type(S)[] # list for generators in S
    for fi in F # go through all generators f_i in F in R to map them into S
        if fi isa Union{PolyRingElem, MPolyRingElem}
            push!(F_S, phi(fi)) # polynomials are mapped into S by phi and appended
        else
            push!(F_S, S(K(fi))) # constants are coerced into K and then into S
        end
    end
    J_F = ideal(S, [F_S[i] - y[i] for i in 1:m]) # J_F = <f_1 - y_1, ..., f_m - y_m>

    # 1. compute a groebner basis of J_F using the lex order x_1 > ... > x_n > y_1 > ... > y_m.
    GG = groebner_basis(J_F; ordering = lex(S))

    # 2. keep the basis elements which contain no x-variable
    GG_y_in_S = [
        g for g in GG # goes through all groebner basis elements of GG
        if all(alpha[i] == 0
               for alpha in AbstractAlgebra.exponent_vectors(g)
               for i in 1:n) # exponent of all x_1, ..., x_n in g must be 0
    ] # then all g_i left in GG_y only depend on y_1, ..., y_m 

    # construct T = k[y_1, ..., y_m] and map GG_y from S into T
    T, Y = polynomial_ring(K, [Symbol("y_$i") for i in 1:m])
    # define homomorphims psi : S = k[x_1, ..., x_n, y_1, ..., y_m] -> T = k[Y_1, ..., Y_m]
    # x_i |-> 0, y_i |-> Y_i
    psi = hom(S, T, vcat(fill(zero(T), n), Y))
    # map all g_i into T 
    GG_y = [psi(g) for g in GG_y_in_S]

    # 3. I_F is generated by GG_y and GG_y is its groebner basis
    I_F = ideal(T, GG_y) # I_F <= T is generated by GG_y
    return I_F, GG_y # return ideal of relations I_F and its groebner basis GG_y
end
